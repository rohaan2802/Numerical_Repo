import numpy as np
from math import factorial

# ---------- common helpers ----------
def f(x):
    return np.exp(-x/3.0) * (np.sin(2*x) + 1.5)

def make_nodes(n=9, a=0.0, b=4.0):
    x = np.linspace(a, b, n)
    y = f(x)
    return x, y

def mae(y_true, y_pred):
    return float(np.mean(np.abs(y_true - y_pred)))

# ---------- Part A: Lagrange ----------
def lagrange_eval(xn, yn, xq):
    """
    Direct Lagrange basis evaluation (O(n^2)).
    """
    xn = np.asarray(xn, float)
    yn = np.asarray(yn, float)
    xq = np.atleast_1d(xq).astype(float)
    n = len(xn)

    yq = np.zeros_like(xq)
    for j, x in enumerate(xq):
        total = 0.0
        for i in range(n):
            Li = 1.0
            for k in range(n):
                if k != i:
                    Li *= (x - xn[k]) / (xn[i] - xn[k])
            total += yn[i] * Li
        yq[j] = total

    return yq if yq.size > 1 else yq.item()

# ---------- Part B: Newton (divided differences) ----------
def newton_divdiff_coeffs(xn, yn):
    """
    Return coefficients c0..c_{n-1} of Newton form using divided differences.
    """
    xn = np.asarray(xn, float)
    yn = np.asarray(yn, float)
    coef = yn.astype(float).copy()

    n = len(xn)
    for j in range(1, n):
        for i in range(n - 1, j - 1, -1):
            coef[i] = (coef[i] - coef[i - 1]) / (xn[i] - xn[i - j])

    return coef


def newton_eval(xn, coef, xq):
    """
    Evaluate Newton polynomial using nested multiplication (Horner style).
    """
    xn = np.asarray(xn, float)
    coef = np.asarray(coef, float)
    xq = np.atleast_1d(xq).astype(float)

    yq = np.zeros_like(xq)
    n = len(coef)

    for k, x in enumerate(xq):
        value = coef[-1]
        for j in range(n - 2, -1, -1):
            value = coef[j] + (x - xn[j]) * value
        yq[k] = value

    return yq if yq.size > 1 else yq.item()



# ---------- Part C: Newton forward/backward (equal spacing) ----------
def forward_diff_table(y):
    """
    Return list [Δ^0 y, Δ^1 y, ..., Δ^{n-1} y]
    """
    y = np.asarray(y, float).copy()
    table = [y]

    for k in range(1, len(y)):
        table.append(np.diff(table[-1]))

    return table


def newton_forward_eval(x0, h, table, xq):
    """
    Forward Newton polynomial with u = (x - x0)/h.
    Uses falling factorial u(u-1)(u-2)...
    """
    xq = np.atleast_1d(xq).astype(float)
    yq = np.zeros_like(xq)

    n = len(table)

    for k, x in enumerate(xq):
        u = (x - x0) / h
        value = table[0][0]   # y0
        prod = 1.0

        for m in range(1, n):
            prod *= (u - (m - 1))           # falling product
            value += prod * table[m][0] / factorial(m)

        yq[k] = value

    return yq if yq.size > 1 else yq.item()


def newton_backward_eval(xn, h, table, xq):
    """
    Backward Newton polynomial with v = (x - xn)/h.
    Uses rising factorial v(v+1)(v+2)...
    """
    xq = np.atleast_1d(xq).astype(float)
    yq = np.zeros_like(xq)

    n = len(table)

    for k, x in enumerate(xq):
        v = (x - xn) / h
        value = table[0][-1]  # y_n
        prod = 1.0

        for m in range(1, n):
            prod *= (v + (m - 1))           # rising product
            diff_last = table[m][-1]
            value += prod * diff_last / factorial(m)

        yq[k] = value

    return yq if yq.size > 1 else yq.item()


# ---------- Part D: Linear & Natural Cubic Splines ----------
def linear_spline_eval(xn, yn, xq):
    """
    Piecewise linear interpolation using searchsorted.
    """
    xn = np.asarray(xn, float)
    yn = np.asarray(yn, float)
    xq = np.atleast_1d(xq).astype(float)

    n = len(xn)
    # For each xq, find the left interval index
    idx = np.searchsorted(xn, xq) - 1
    idx = np.clip(idx, 0, n - 2)

    x0 = xn[idx]
    x1 = xn[idx + 1]
    y0 = yn[idx]
    y1 = yn[idx + 1]

    t = (xq - x0) / (x1 - x0)
    yq = y0 + t * (y1 - y0)

    return yq if yq.size > 1 else yq.item()


def natural_cubic_spline_build(xn, yn):
    """
    Build natural cubic spline second derivatives M.
    M[0] = M[n-1] = 0 (natural boundary conditions).
    """
    xn = np.asarray(xn, float)
    yn = np.asarray(yn, float)
    n = len(xn)

    h = np.diff(xn)
    M = np.zeros(n)

    if n > 2:
        A = np.zeros((n - 2, n - 2))
        rhs = np.zeros(n - 2)

        for i in range(n - 2):
            A[i, i] = 2 * (h[i] + h[i + 1])
            if i > 0:
                A[i, i - 1] = h[i]
            if i < n - 3:
                A[i, i + 1] = h[i + 1]

            rhs[i] = 6 * ((yn[i + 2] - yn[i + 1]) / h[i + 1] -
                          (yn[i + 1] - yn[i]) / h[i])

        M[1:-1] = np.linalg.solve(A, rhs)

    return (xn, yn, M)


def natural_cubic_spline_eval(spline, xq):
    """
    Evaluate natural cubic spline.
    """
    xn, yn, M = spline
    xn = np.asarray(xn, float)
    yn = np.asarray(yn, float)
    M = np.asarray(M, float)

    xq = np.atleast_1d(xq).astype(float)
    n = len(xn)

    idx = np.searchsorted(xn, xq) - 1
    idx = np.clip(idx, 0, n - 2)

    x0 = xn[idx]
    x1 = xn[idx + 1]
    h = x1 - x0

    y0 = yn[idx]
    y1 = yn[idx + 1]
    M0 = M[idx]
    M1 = M[idx + 1]

    a = (x1 - xq) / h
    b = (xq - x0) / h

    term1 = M0 * (x1 - xq)**3 / (6*h)
    term2 = M1 * (xq - x0)**3 / (6*h)
    term3 = (y0 - M0 * h**2 / 6) * a
    term4 = (y1 - M1 * h**2 / 6) * b

    yq = term1 + term2 + term3 + term4
    return yq if yq.size > 1 else yq.item()


# ---------- Part E: Least-squares polynomial fit ----------
def design_matrix_poly(x, degree):
    """
    Build Vandermonde-like matrix [1, x, x^2, ... x^degree].
    Each column k is x**k.
    """
    x = np.asarray(x, float)
    cols = [x**k for k in range(degree + 1)]
    X = np.vstack(cols).T
    return X


def poly_least_squares_fit(x, y, degree):
    """
    Solve least-squares system Xb ≈ y.
    Returns b (coefficients in ascending powers).
    """
    x = np.asarray(x, float)
    y = np.asarray(y, float)
    X = design_matrix_poly(x, degree)
    b, _, _, _ = np.linalg.lstsq(X, y, rcond=None)
    return b


def poly_eval(b, xq):
    """
    Evaluate polynomial with coefficients b (ascending powers).
    P(x) = sum b[k] * x^k
    """
    b = np.asarray(b, float)
    xq = np.asarray(xq, float)
    yq = np.zeros_like(xq)

    for k, bk in enumerate(b):
        yq += bk * (xq ** k)

    return yq


# ---------- Part F: Non-polynomial exponential fit ----------
def fit_exponential(x, y):
    """
    Fit y ≈ A * exp(Bx), y>0.
    Linearize: ln(y) = ln(A) + Bx and do least squares.
    """
    x = np.asarray(x, float)
    y = np.asarray(y, float)

    # Only use positive y-values (required for log)
    mask = y > 0
    x_pos = x[mask]
    y_pos = y[mask]

    ln_y = np.log(y_pos)

    # Build linear system
    # ln(y) = lnA + Bx  ->  [1, x] [lnA, B]^T
    X = np.vstack([np.ones_like(x_pos), x_pos]).T

    coeffs, _, _, _ = np.linalg.lstsq(X, ln_y, rcond=None)
    lnA, B = coeffs

    A = np.exp(lnA)
    return A, B


def eval_exponential(A, B, xq):
    return A * np.exp(B * np.asarray(xq, float))

